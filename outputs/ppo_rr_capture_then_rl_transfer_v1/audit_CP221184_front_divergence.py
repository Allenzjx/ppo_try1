"""Sealed-source, bounded prefix audit; standard library only, no actor/Isaac.

Reads capture, policy, native streams only through first P06; records compact
actual measurements and selected native receipts. Never modifies source data.
This revised v2 draft has not been executed. The preserved non-v2 JSON/Markdown
were generated by the earlier script; use the verified summary for its
post-observation nominal timing clarification. Do not run alongside live Isaac.
"""
from pathlib import Path
